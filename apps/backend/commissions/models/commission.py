"""
Canonical commission model for Univa.

A Commission represents a financial entitlement generated by a
business event.

The originating domain may be:

    - Real Estate
    - Transport
    - Logistics
    - E-commerce
    - Referrals
    - Other Univa domains

This model intentionally contains no domain-specific foreign keys.

A Commission answers:

    Who is entitled?
    Which commission plan was used?
    What was the calculation basis?
    What amount was calculated?
    What is the lifecycle state?

Payment and settlement are separate concerns.
"""

import uuid
from decimal import Decimal

from django.core.exceptions import ValidationError
from django.core.validators import MinValueValidator
from django.db import models
from django.utils.translation import gettext_lazy as _

from .plan import CommissionPlan


class Commission(models.Model):
    """
    A calculated commission entitlement.

    The commission records the financial result of applying a
    CommissionPlan to a business event.

    It does not perform the calculation itself and it does not
    represent payment or settlement.
    """

    class Status(models.TextChoices):
        PENDING = "pending", _("Pending")
        CALCULATED = "calculated", _("Calculated")
        APPROVED = "approved", _("Approved")
        PAYABLE = "payable", _("Payable")
        SETTLED = "settled", _("Settled")
        CANCELLED = "cancelled", _("Cancelled")
        REVERSED = "reversed", _("Reversed")

    class SourceType(models.TextChoices):
        REAL_ESTATE = "real_estate", _("Real Estate")
        TRANSPORT = "transport", _("Transport")
        LOGISTICS = "logistics", _("Logistics")
        ECOMMERCE = "ecommerce", _("E-commerce")
        REFERRAL = "referral", _("Referral")
        OTHER = "other", _("Other")

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    plan = models.ForeignKey(
        CommissionPlan,
        on_delete=models.PROTECT,
        related_name="commissions",
    )

    beneficiary = models.ForeignKey(
        "accounts.User",
        on_delete=models.PROTECT,
        related_name="commissions",
    )

    source_type = models.CharField(
        max_length=30,
        choices=SourceType.choices,
        db_index=True,
    )

    source_id = models.CharField(
        max_length=100,
        db_index=True,
    )

    source_reference = models.CharField(
        max_length=150,
        blank=True,
    )

    calculation_basis = models.DecimalField(
        max_digits=20,
        decimal_places=2,
        validators=[
            MinValueValidator(Decimal("0")),
        ],
    )

    rate = models.DecimalField(
        max_digits=7,
        decimal_places=4,
        null=True,
        blank=True,
        validators=[
            MinValueValidator(Decimal("0")),
        ],
    )

    calculated_amount = models.DecimalField(
        max_digits=20,
        decimal_places=2,
        validators=[
            MinValueValidator(Decimal("0")),
        ],
    )

    currency = models.CharField(
        max_length=3,
        default="NGN",
    )

    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.PENDING,
        db_index=True,
    )

    notes = models.TextField(
        blank=True,
    )

    metadata = models.JSONField(
        default=dict,
        blank=True,
    )

    calculated_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    approved_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    payable_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    settled_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    reversed_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    class Meta:
        ordering = ["-created_at"]

        indexes = [
            models.Index(
                fields=["beneficiary", "status"],
                name="comm_beneficiary_status_idx",
            ),
            models.Index(
                fields=["source_type", "source_id"],
                name="commission_source_idx",
            ),
            models.Index(
                fields=["plan", "status"],
                name="commission_plan_status_idx",
            ),
            models.Index(
                fields=["status", "created_at"],
                name="commission_status_created_idx",
            ),
        ]

    def __str__(self):
        return (
            f"Commission {self.id} - "
            f"{self.beneficiary} - "
            f"{self.calculated_amount} {self.currency}"
        )

    def clean(self):
        super().clean()

        if self.calculation_basis < 0:
            raise ValidationError(
                {
                    "calculation_basis": _(
                        "Calculation basis cannot be negative."
                    )
                }
            )

        if self.calculated_amount < 0:
            raise ValidationError(
                {
                    "calculated_amount": _(
                        "Commission amount cannot be negative."
                    )
                }
            )

        if self.rate is not None and self.rate < 0:
            raise ValidationError(
                {
                    "rate": _(
                        "Commission rate cannot be negative."
                    )
                }
            )

        if (
            self.status == self.Status.SETTLED
            and not self.settled_at
        ):
            raise ValidationError(
                {
                    "settled_at": _(
                        "A settled commission must have "
                        "a settlement timestamp."
                    )
                }
            )

        if (
            self.status == self.Status.REVERSED
            and not self.reversed_at
        ):
            raise ValidationError(
                {
                    "reversed_at": _(
                        "A reversed commission must have "
                        "a reversal timestamp."
                    )
                }
            )

    @property
    def is_pending(self):
        return self.status == self.Status.PENDING

    @property
    def is_calculated(self):
        return self.status == self.Status.CALCULATED

    @property
    def is_approved(self):
        return self.status == self.Status.APPROVED

    @property
    def is_payable(self):
        return self.status == self.Status.PAYABLE

    @property
    def is_settled(self):
        return self.status == self.Status.SETTLED

    @property
    def is_cancelled(self):
        return self.status == self.Status.CANCELLED

    @property
    def is_reversed(self):
        return self.status == self.Status.REVERSED