"""
Canonical notification event constants for Univa.

Event identifiers use the stable:

    MODULE.ACTION

format.

Examples:

    ORDER.CREATED
    PAYMENT.SUCCESSFUL
    TRANSPORT.RIDE_ACCEPTED
    CHAT.MESSAGE_RECEIVED

These identifiers are persisted in NotificationEvent records and may
also be consumed by other applications or integrations.

IMPORTANT
---------
Once an event identifier is used in production, do not rename it.
Changing an existing identifier can break persisted events and
external integrations.
"""

