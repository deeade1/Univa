# apps/backend/notifications/models/notification.py

"""
User notification model for Univa.

A UserNotification represents an in-app notification delivered to a
specific user.

The model is intentionally module-agnostic and can represent
notifications generated by:

    - Accounts
    - Banking
    - Transport
    - E-commerce
    - Real Estate
    - Payments
    - Social
    - Chat
    - Blog
    - Community
    - System
"""

from __future__ import annotations

from django.conf import settings
from django.db import models
from django.utils import timezone


class UserNotification(models.Model):
    """
    A notification delivered to a specific Univa user.
    """

    # ========================================================================
    # ENUMS
    # ========================================================================

    class NotificationType(models.TextChoices):
        INFO = "info", "Information"
        SUCCESS = "success", "Success"
        WARNING = "warning", "Warning"
        ERROR = "error", "Error"
        SYSTEM = "system", "System"

    class Priority(models.TextChoices):
        LOW = "low", "Low"
        NORMAL = "normal", "Normal"
        HIGH = "high", "High"
        URGENT = "urgent", "Urgent"

    # ========================================================================
    # RECIPIENT
    # ========================================================================

    recipient = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="notifications",
        db_index=True,
        help_text="User who receives this notification.",
    )

    # ========================================================================
    # SOURCE EVENT
    # ========================================================================

    event = models.ForeignKey(
        "notifications.NotificationEvent",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="notifications",
        help_text="Source notification event.",
    )

    # ========================================================================
    # NOTIFICATION IDENTITY
    # ========================================================================

    module = models.CharField(
        max_length=50,
        db_index=True,
        help_text="Univa module that generated the notification.",
    )

    notification_type = models.CharField(
        max_length=20,
        choices=NotificationType.choices,
        default=NotificationType.INFO,
    )

    priority = models.CharField(
        max_length=20,
        choices=Priority.choices,
        default=Priority.NORMAL,
    )

    # ========================================================================
    # CONTENT
    # ========================================================================

    title = models.CharField(
        max_length=255,
    )

    message = models.TextField()

    # ========================================================================
    # NAVIGATION / CONTEXT
    # ========================================================================

    action_url = models.CharField(
        max_length=500,
        blank=True,
        help_text=(
            "Deep link or frontend route opened when "
            "the notification is selected."
        ),
    )

    metadata = models.JSONField(
        default=dict,
        blank=True,
        help_text="Additional structured data for the frontend.",
    )

    # ========================================================================
    # STATE
    # ========================================================================

    is_read = models.BooleanField(
        default=False,
    )

    read_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    is_archived = models.BooleanField(
        default=False,
    )

    archived_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    # ========================================================================
    # TIMESTAMPS
    # ========================================================================

    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    # ========================================================================
    # META
    # ========================================================================

    class Meta:
        ordering = ["-created_at"]

        constraints = [
            models.UniqueConstraint(
                fields=["event", "recipient"],
                name="unique_event_recipient_notification",
            ),
        ]

        indexes = [
            models.Index(
                fields=[
                    "recipient",
                    "is_read",
                    "created_at",
                ],
                name="notif_user_read_idx",
            ),
            models.Index(
                fields=[
                    "recipient",
                    "is_archived",
                    "created_at",
                ],
                name="notif_user_arch_idx",
            ),
            models.Index(
                fields=[
                    "recipient",
                    "module",
                    "created_at",
                ],
                name="notif_user_module_idx",
            ),
            models.Index(
                fields=[
                    "event",
                ],
                name="notif_event_idx",
            ),
            models.Index(
                fields=[
                    "priority",
                    "created_at",
                ],
                name="notif_priority_idx",
            ),
            models.Index(
                fields=[
                    "created_at",
                ],
                name="notif_created_idx",
            ),
        ]

    # ========================================================================
    # STRING REPRESENTATION
    # ========================================================================

    def __str__(self) -> str:
        return f"{self.title} → {self.recipient}"

    # ========================================================================
    # STATE PROPERTIES
    # ========================================================================

    @property
    def is_unread(self) -> bool:
        """
        Return True when the notification has not been read.
        """
        return not self.is_read

    @property
    def is_active(self) -> bool:
        """
        Return True when the notification is not archived.
        """
        return not self.is_archived

    # ========================================================================
    # READ STATE
    # ========================================================================

    def mark_as_read(self) -> None:
        """
        Mark this notification as read.
        """

        if self.is_read:
            return

        self.is_read = True
        self.read_at = timezone.now()

        self.save(
            update_fields=[
                "is_read",
                "read_at",
                "updated_at",
            ]
        )

    def mark_as_unread(self) -> None:
        """
        Mark this notification as unread.
        """

        if not self.is_read and self.read_at is None:
            return

        self.is_read = False
        self.read_at = None

        self.save(
            update_fields=[
                "is_read",
                "read_at",
                "updated_at",
            ]
        )

    # ========================================================================
    # ARCHIVE STATE
    # ========================================================================

    def archive(self) -> None:
        """
        Archive this notification without deleting it.
        """

        if self.is_archived:
            return

        self.is_archived = True
        self.archived_at = timezone.now()

        self.save(
            update_fields=[
                "is_archived",
                "archived_at",
                "updated_at",
            ]
        )

    def unarchive(self) -> None:
        """
        Restore an archived notification.
        """

        if not self.is_archived and self.archived_at is None:
            return

        self.is_archived = False
        self.archived_at = None

        self.save(
            update_fields=[
                "is_archived",
                "archived_at",
                "updated_at",
            ]
        )