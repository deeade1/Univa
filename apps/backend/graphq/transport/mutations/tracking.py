# apps/backend/graphq/transport/mutations/tracking.py
"""
Tracking & TrackingEvent mutations.

Both models inherit LocationModel. Location updates must go through
`update_location()` — writing `location_point` / `latitude` / `longitude`
directly bypasses the model's validation and `source` tracking.

Status changes on Tracking are routed through `Tracking.update_status()`,
which:
    - creates the corresponding TrackingEvent
    - cascades status to the linked Package / Delivery
    - updates `last_updated`
"""

from django.core.exceptions import ValidationError
from django.db import transaction
from django.utils import timezone
from graphene import relay
import graphene
from graphql import GraphQLError
from graphql_relay import from_global_id

from graphq.transport.types.tracking import (
    TrackingNode,
    TrackingEventNode,
)
from graphq.transport.types.package  import  PackageNode
 
from graphq.transport.types.delivery import DeliveryNode

from transport.models.delivery.tracking import Tracking, TrackingEvent
from transport.models.delivery.package import Package
from transport.models.delivery.delivery import Delivery


# =============================================================================
# Helpers
# =============================================================================

_TERMINAL_STATUSES = {
    Tracking.Status.DELIVERED,
    Tracking.Status.DELIVERY_CONFIRMED,
    Tracking.Status.COMPLETED,
    Tracking.Status.CANCELLED,
    Tracking.Status.RETURNED,
    Tracking.Status.RETURN_TO_SENDER,
    Tracking.Status.LOST,
    Tracking.Status.DAMAGED,
}

_ALLOWED_STATUSES = {choice[0] for choice in Tracking.Status.choices}


def _resolve_tracking(global_id, *, lock=False):
    try:
        _, pk = from_global_id(global_id)
    except Exception:
        raise GraphQLError("Invalid tracking_id.")
    qs = Tracking.objects.all()
    if lock:
        qs = qs.select_for_update()
    try:
        return qs.get(pk=pk)
    except Tracking.DoesNotExist:
        raise GraphQLError("Tracking record not found.")


def _resolve_event(global_id, *, lock=False):
    try:
        _, pk = from_global_id(global_id)
    except Exception:
        raise GraphQLError("Invalid tracking_event_id.")
    qs = TrackingEvent.objects.all()
    if lock:
        qs = qs.select_for_update()
    try:
        return qs.get(pk=pk)
    except TrackingEvent.DoesNotExist:
        raise GraphQLError("Tracking event not found.")


def _assert_can_manage(tracking, user):
    """
    Only staff, the assigned provider, or (for package/delivery-linked
    tracking) the customer who owns the related object may modify.
    """
    if not user.is_authenticated:
        raise GraphQLError("Authentication required.")
    if user.is_staff:
        return

    provider = getattr(user, "service_provider", None)

    # Provider assigned via the legacy ServiceRequest link.
    sr = getattr(tracking, "service_request", None)
    if sr is not None:
        if sr.provider_id and provider and sr.provider_id == provider.pk:
            return
        if sr.customer_id == user.pk:
            return

    # Otherwise resolve the owner via package -> delivery -> customer.
    if tracking.package_id:
        delivery = getattr(tracking.package, "delivery", None)
        if delivery is not None and delivery.customer_id == user.pk:
            return

    if tracking.delivery_id and tracking.delivery.customer_id == user.pk:
        return

    raise GraphQLError("Not authorized to modify this tracking record.")


def _validate_status(status):
    if status not in _ALLOWED_STATUSES:
        raise GraphQLError(
            f"Invalid status '{status}'. Allowed: "
            f"{', '.join(sorted(_ALLOWED_STATUSES))}."
        )


def _trigger_event_subscription(event):
    """Best-effort subscription trigger."""
    try:
        from graphq.transport.subscriptions import TrackingEventCreatedSubscription
        TrackingEventCreatedSubscription.trigger(event)
    except ImportError:
        pass
    except Exception:
        pass


def _trigger_tracking_status_subscription(tracking):
    try:
        from graphq.transport.subscriptions import OnTrackingStatusChanged
        OnTrackingStatusChanged.trigger(tracking)
    except ImportError:
        pass
    except Exception:
        pass


