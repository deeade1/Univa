class UpdateTrackingLocation(relay.ClientIDMutation):
    """
    Push a new location onto a Tracking record without changing status.

    Uses `LocationModel.update_location()` so the location source and
    validation are recorded consistently.
    """

    class Input:
        tracking_id = graphene.ID(required=True)
        lat = graphene.Float(required=True)
        lng = graphene.Float(required=True)
        address = graphene.String()
        accuracy = graphene.Float()
        source = graphene.String()

    tracking = graphene.Field(TrackingNode)
    tracking_event = graphene.Field(TrackingEventNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(
        cls,
        root,
        info,
        tracking_id,
        lat,
        lng,
        address=None,
        accuracy=None,
        source="gps",
    ):
        me = info.context.user
        tracking = _resolve_tracking(tracking_id, lock=True)
        _assert_can_manage(tracking, me)

        if not (-90 <= lat <= 90):
            raise GraphQLError("Latitude must be between -90 and 90.")
        if not (-180 <= lng <= 180):
            raise GraphQLError("Longitude must be between -180 and 180.")

        try:
            tracking.update_location(
                latitude=lat,
                longitude=lng,
                address=address,
                accuracy=accuracy,
                source=source or "gps",
            )
        except (ValueError, ValidationError) as exc:
            raise GraphQLError(str(exc))

        # Log a lightweight event marking the location update. We keep
        # the current status so we don't cascade incorrectly.
        event = TrackingEvent.objects.create(
            tracking=tracking,
            status=tracking.current_status,
            description="Location updated",
            latitude=lat,
            longitude=lng,
            address=address,
        )

        _trigger_event_subscription(event)

        return cls(
            tracking=tracking,
            tracking_event=event,
            success=True,
            message="Location updated.",
        )


