class UpdateTracking(relay.ClientIDMutation):
    """
    Update the metadata-level fields of a Tracking record.

    Status is NOT updated here — use `UpdateTrackingStatus`.
    """

    class Input:
        tracking_id = graphene.ID(required=True)

        estimated_delivery = graphene.DateTime()
        priority = graphene.String()
        carrier_name = graphene.String()
        carrier_tracking_number = graphene.String()
        signature_required = graphene.Boolean()
        notes = graphene.String()
        metadata = graphene.JSONString()

    tracking = graphene.Field(TrackingNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, tracking_id, **input):
        me = info.context.user
        tracking = _resolve_tracking(tracking_id, lock=True)
        _assert_can_manage(tracking, me)

        if tracking.current_status in _TERMINAL_STATUSES and not me.is_staff:
            raise GraphQLError(
                f"Cannot edit a tracking record in terminal state "
                f"'{tracking.current_status}'."
            )

        update_fields = []

        simple_map = {
            "estimated_delivery": "estimated_delivery",
            "carrier_name": "carrier_name",
            "carrier_tracking_number": "carrier_tracking_number",
            "notes": "notes",
        }
        for input_key, model_field in simple_map.items():
            if input_key in input and input[input_key] is not None:
                setattr(tracking, model_field, input[input_key])
                update_fields.append(model_field)

        if "priority" in input and input["priority"] is not None:
            if input["priority"] not in dict(Tracking.Priority.choices):
                raise GraphQLError(
                    f"priority must be one of: "
                    f"{', '.join(dict(Tracking.Priority.choices).keys())}."
                )
            tracking.priority = input["priority"]
            update_fields.append("priority")

        if "signature_required" in input and input["signature_required"] is not None:
            tracking.signature_required = bool(input["signature_required"])
            update_fields.append("signature_required")

        if "metadata" in input and input["metadata"] is not None:
            if not isinstance(input["metadata"], dict):
                raise GraphQLError("metadata must be an object.")
            tracking.metadata = {**(tracking.metadata or {}), **input["metadata"]}
            update_fields.append("metadata")

        if not update_fields:
            return cls(
                tracking=tracking,
                success=True,
                message="Nothing to update.",
            )

        try:
            tracking.full_clean()
        except ValidationError as exc:
            raise GraphQLError(f"Validation failed: {exc.message_dict}")

        tracking.save(update_fields=update_fields)

        return cls(
            tracking=tracking,
            success=True,
            message="Tracking updated.",
        )


