class ConfirmDelivery(relay.ClientIDMutation):
    """
    Confirm delivery with optional signature and photo.

    `signature_image` / `delivery_photo` accept file references — see
    your file upload mechanism for how binary data is transported.
    Here we accept them as Django File objects resolved upstream.
    """

    class Input:
        tracking_id = graphene.ID(required=True)
        signature_name = graphene.String()
        signature_image = graphene.String()  # storage ref
        delivery_photo = graphene.String()   # storage ref
        lat = graphene.Float()
        lng = graphene.Float()
        address = graphene.String()

    tracking = graphene.Field(TrackingNode)
    tracking_event = graphene.Field(TrackingEventNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, tracking_id, **input):
        me = info.context.user
        tracking = _resolve_tracking(tracking_id, lock=True)
        _assert_can_manage(tracking, me)

        if tracking.is_delivered:
            return cls(
                tracking=tracking,
                tracking_event=None,
                success=True,
                message="Delivery is already confirmed.",
            )

        # Image handling is delegated to your upload pipeline; this
        # mutation assumes the caller resolves storage refs to File
        # objects and hands them over out-of-band.
        signature_image = None
        delivery_photo = None

        if (input.get("lat") is None) ^ (input.get("lng") is None):
            raise GraphQLError("Provide both lat and lng, or neither.")

        try:
            event = tracking.confirm_delivery(
                signature_name=input.get("signature_name"),
                signature_image=signature_image,
                delivery_photo=delivery_photo,
                lat=input.get("lat"),
                lng=input.get("lng"),
                address=input.get("address"),
            )
        except (ValueError, ValidationError) as exc:
            raise GraphQLError(str(exc))

        _trigger_event_subscription(event)
        _trigger_tracking_status_subscription(tracking)

        return cls(
            tracking=tracking,
            tracking_event=event,
            success=True,
            message="Delivery confirmed.",
        )


