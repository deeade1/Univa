class CreateTrackingEvent(relay.ClientIDMutation):
    """
    Add a custom event to a tracking record.

    For status transitions, prefer `UpdateTrackingStatus` — this mutation
    is for supplementary events that don't change the current status.
    """

    class Input:
        tracking_id = graphene.ID(required=True)
        status = graphene.String(required=True)
        description = graphene.String()
        event_code = graphene.String()
        notes = graphene.String()

        lat = graphene.Float()
        lng = graphene.Float()
        address = graphene.String()

        timestamp = graphene.DateTime()
        metadata = graphene.JSONString()

    tracking_event = graphene.Field(TrackingEventNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, tracking_id, status, **input):
        me = info.context.user
        tracking = _resolve_tracking(tracking_id, lock=True)
        _assert_can_manage(tracking, me)

        _validate_status(status)

        if (input.get("lat") is None) ^ (input.get("lng") is None):
            raise GraphQLError("Provide both lat and lng, or neither.")

        try:
            event = TrackingEvent(
                tracking=tracking,
                status=status,
                description=input.get("description") or "",
                event_code=input.get("event_code") or "",
                notes=input.get("notes") or "",
                address=input.get("address") or "",
                metadata=input.get("metadata") or {},
            )
            if input.get("timestamp"):
                event.timestamp = input["timestamp"]
            if input.get("lat") is not None:
                event.latitude = input["lat"]
                event.longitude = input["lng"]
            event.full_clean()
            event.save()
        except ValidationError as exc:
            raise GraphQLError(f"Validation failed: {exc.message_dict}")

        _trigger_event_subscription(event)

        return cls(
            tracking_event=event,
            success=True,
            message="Tracking event created.",
        )


class UpdateTrackingEvent(relay.ClientIDMutation):
    """Update the descriptive fields of a TrackingEvent."""

    class Input:
        tracking_event_id = graphene.ID(required=True)

        status = graphene.String()
        description = graphene.String()
        event_code = graphene.String()
        notes = graphene.String()

        lat = graphene.Float()
        lng = graphene.Float()
        address = graphene.String()

        timestamp = graphene.DateTime()
        metadata = graphene.JSONString()

    tracking_event = graphene.Field(TrackingEventNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, tracking_event_id, **input):
        me = info.context.user
        event = _resolve_event(tracking_event_id, lock=True)
        _assert_can_manage(event.tracking, me)

        update_fields = []

        if "status" in input and input["status"] is not None:
            _validate_status(input["status"])
            event.status = input["status"]
            update_fields.append("status")

        simple_map = {
            "description": "description",
            "event_code": "event_code",
            "notes": "notes",
            "address": "address",
            "timestamp": "timestamp",
        }
        for input_key, model_field in simple_map.items():
            if input_key in input and input[input_key] is not None:
                setattr(event, model_field, input[input_key])
                update_fields.append(model_field)

        if "lat" in input and input["lat"] is not None:
            if input.get("lng") is None:
                raise GraphQLError("lng is required when updating lat.")
            event.latitude = input["lat"]
            event.longitude = input["lng"]
            update_fields.extend(["latitude", "longitude"])

        if "metadata" in input and input["metadata"] is not None:
            if not isinstance(input["metadata"], dict):
                raise GraphQLError("metadata must be an object.")
            event.metadata = {**(event.metadata or {}), **input["metadata"]}
            update_fields.append("metadata")

        if not update_fields:
            return cls(
                tracking_event=event,
                success=True,
                message="Nothing to update.",
            )

        try:
            event.full_clean()
        except ValidationError as exc:
            raise GraphQLError(f"Validation failed: {exc.message_dict}")

        event.save(update_fields=sorted(set(update_fields)))

        return cls(
            tracking_event=event,
            success=True,
            message="Tracking event updated.",
        )


