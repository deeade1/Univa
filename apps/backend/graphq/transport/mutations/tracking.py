class UpdateTrackingStatus(relay.ClientIDMutation):
    """
    Transition a Tracking record to a new status.

    Delegates to `Tracking.update_status()`, which:
        - creates the associated TrackingEvent
        - cascades status to Package / Delivery
        - updates `last_updated`

    Terminal statuses cannot be escaped by non-staff.
    """

    class Input:
        tracking_id = graphene.ID(required=True)
        status = graphene.String(required=True)
        description = graphene.String()
        lat = graphene.Float()
        lng = graphene.Float()
        address = graphene.String()

    tracking = graphene.Field(TrackingNode)
    tracking_event = graphene.Field(TrackingEventNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(
        cls,
        root,
        info,
        tracking_id,
        status,
        description=None,
        lat=None,
        lng=None,
        address=None,
    ):
        me = info.context.user
        tracking = _resolve_tracking(tracking_id, lock=True)
        _assert_can_manage(tracking, me)

        _validate_status(status)

        # Terminal → non-terminal requires staff.
        if (
            tracking.current_status in _TERMINAL_STATUSES
            and status not in _TERMINAL_STATUSES
            and not me.is_staff
        ):
            raise GraphQLError(
                f"Cannot leave terminal state '{tracking.current_status}'."
            )

        if (lat is None) ^ (lng is None):
            raise GraphQLError("Provide both lat and lng, or neither.")

        try:
            event = tracking.update_status(
                new_status=status,
                location=address,
                description=description,
                lat=lat,
                lng=lng,
                address=address,
            )
        except (ValueError, ValidationError) as exc:
            raise GraphQLError(str(exc))

        _trigger_event_subscription(event)
        _trigger_tracking_status_subscription(tracking)

        return cls(
            tracking=tracking,
            tracking_event=event,
            success=True,
            message=f"Status updated to {status}.",
        )


