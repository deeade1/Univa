class CreateTracking(relay.ClientIDMutation):
    """
    Create a Tracking record.

    Must be linked to either a Package, a Delivery, or (legacy) a
    ServiceRequest. `tracking_number` is auto-generated by the model if
    left blank; `estimated_delivery` is required.
    """

    class Input:
        package_id = graphene.ID()
        delivery_id = graphene.ID()
        service_request_id = graphene.ID()  # legacy

        estimated_delivery = graphene.DateTime(required=True)
        priority = graphene.String()

        carrier_name = graphene.String()
        carrier_tracking_number = graphene.String()

        signature_required = graphene.Boolean()
        notes = graphene.String()
        metadata = graphene.JSONString()

    tracking = graphene.Field(TrackingNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, estimated_delivery, **input):
        me = info.context.user
        if not me.is_authenticated:
            raise GraphQLError("Authentication required.")

        package = None
        delivery = None
        service_request = None

        if input.get("package_id"):
            try:
                _, pk = from_global_id(input["package_id"])
                package = Package.objects.get(pk=pk)
            except Package.DoesNotExist:
                raise GraphQLError("Package not found.")
            except Exception:
                raise GraphQLError("Invalid package_id.")

        if input.get("delivery_id"):
            try:
                _, pk = from_global_id(input["delivery_id"])
                delivery = Delivery.objects.get(pk=pk)
            except Delivery.DoesNotExist:
                raise GraphQLError("Delivery not found.")
            except Exception:
                raise GraphQLError("Invalid delivery_id.")

        if input.get("service_request_id"):
            from transport.models.core.service_request import ServiceRequest
            try:
                _, pk = from_global_id(input["service_request_id"])
                service_request = ServiceRequest.objects.get(pk=pk)
            except ServiceRequest.DoesNotExist:
                raise GraphQLError("Service request not found.")
            except Exception:
                raise GraphQLError("Invalid service_request_id.")

        if not (package or delivery or service_request):
            raise GraphQLError(
                "Tracking must be linked to a Package, Delivery, "
                "or ServiceRequest."
            )

        # Ownership check: caller must be customer of the linked object
        # or the assigned provider on the service request, or staff.
        if not me.is_staff:
            allowed = False
            provider = getattr(me, "service_provider", None)

            if service_request is not None:
                if service_request.customer_id == me.pk:
                    allowed = True
                elif (
                    service_request.provider_id
                    and provider
                    and service_request.provider_id == provider.pk
                ):
                    allowed = True

            if delivery is not None and delivery.customer_id == me.pk:
                allowed = True

            if package is not None:
                parent_delivery = getattr(package, "delivery", None)
                if parent_delivery is not None and parent_delivery.customer_id == me.pk:
                    allowed = True

            if not allowed:
                raise GraphQLError(
                    "Not authorized to create tracking for this record."
                )

        priority = input.get("priority") or Tracking.Priority.STANDARD
        if priority not in dict(Tracking.Priority.choices):
            raise GraphQLError(
                f"priority must be one of: "
                f"{', '.join(dict(Tracking.Priority.choices).keys())}."
            )

        try:
            tracking = Tracking(
                package=package,
                delivery=delivery,
                service_request=service_request,
                estimated_delivery=estimated_delivery,
                priority=priority,
                carrier_name=input.get("carrier_name") or "",
                carrier_tracking_number=input.get("carrier_tracking_number") or "",
                signature_required=bool(input.get("signature_required")),
                notes=input.get("notes") or "",
                metadata=input.get("metadata") or {},
            )
            # save() auto-generates tracking_number and runs full_clean().
            tracking.save()
        except ValidationError as exc:
            raise GraphQLError(f"Validation failed: {exc.message_dict}")

        return cls(
            tracking=tracking,
            success=True,
            message=f"Tracking created: {tracking.tracking_number}.",
        )


