class CreateWhiteLabelClient(relay.ClientIDMutation):
    """
    Create a WhiteLabelClient and its OneToOne configuration.

    Staff-only. `api_key` is server-generated and returned in the
    response — treat the response as sensitive. The configuration is
    created in the same transaction so the client always has one.
    """

    class Input:
        # Required
        name = graphene.String(required=True)
        domain = graphene.String(required=True)
        company_name = graphene.String(required=True)
        support_email = graphene.String(required=True)

        # Branding
        logo_url = graphene.String()          # ignored on create if no upload pipeline
        primary_color = graphene.String()
        secondary_color = graphene.String()
        font_family = graphene.String()

        # Content
        support_phone = graphene.String()
        terms_of_service = graphene.String()
        privacy_policy = graphene.String()

        # Customization
        custom_css = graphene.String()
        custom_js = graphene.String()

        # Features
        enabled_features = graphene.JSONString()
        custom_features = graphene.JSONString()

        # API
        webhook_url = graphene.String()

        # Configuration (one-to-one)
        theme_mode = graphene.String()
        enable_ride_sharing = graphene.Boolean()
        enable_sustainability_tracking = graphene.Boolean()
        enable_accessibility_features = graphene.Boolean()
        enable_analytics_dashboard = graphene.Boolean()
        payment_gateway = graphene.String()
        custom_domains = graphene.List(graphene.String)
        google_analytics_id = graphene.String()
        facebook_pixel_id = graphene.String()

    white_label_client = graphene.Field(WhiteLabelClientNode)
    white_label_configuration = graphene.Field(WhiteLabelConfigurationNode)
    api_key = graphene.String(
        description="Server-generated. Store securely; not returned on subsequent queries."
    )
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, **input):
        _assert_staff(info.context.user)

        # Basic validation
        _validate_url(input["domain"], "domain")
        _validate_email(input["support_email"], "support_email")
        _validate_url(input.get("terms_of_service"), "terms_of_service")
        _validate_url(input.get("privacy_policy"), "privacy_policy")
        _validate_url(input.get("webhook_url"), "webhook_url")
        _validate_hex_color(input.get("primary_color"), "primary_color")
        _validate_hex_color(input.get("secondary_color"), "secondary_color")

        if WhiteLabelClient.objects.filter(domain=input["domain"]).exists():
            raise GraphQLError("A client with this domain already exists.")

        theme_mode = input.get("theme_mode") or "light"
        if theme_mode not in _ALLOWED_THEME_MODES:
            raise GraphQLError(
                f"theme_mode must be one of: {', '.join(sorted(_ALLOWED_THEME_MODES))}."
            )

        payment_gateway = input.get("payment_gateway") or "stripe"
        if payment_gateway not in _ALLOWED_PAYMENT_GATEWAYS:
            raise GraphQLError(
                f"payment_gateway must be one of: "
                f"{', '.join(sorted(_ALLOWED_PAYMENT_GATEWAYS))}."
            )

        # Generate API key
        api_key = _generate_api_key()

        client_payload = {
            "name": input["name"],
            "domain": input["domain"],
            "company_name": input["company_name"],
            "support_email": input["support_email"],
            "primary_color": input.get("primary_color") or "#3B82F6",
            "secondary_color": input.get("secondary_color") or "#1E40AF",
            "font_family": input.get("font_family") or "Inter",
            "support_phone": input.get("support_phone") or "",
            "terms_of_service": input.get("terms_of_service") or "",
            "privacy_policy": input.get("privacy_policy") or "",
            "custom_css": input.get("custom_css") or "",
            "custom_js": input.get("custom_js") or "",
            "enabled_features": input.get("enabled_features") or {},
            "custom_features": input.get("custom_features") or {},
            "webhook_url": input.get("webhook_url") or "",
            "api_key": api_key,
            "is_active": True,
        }

        try:
            client = WhiteLabelClient.objects.create(**client_payload)
        except ValidationError as exc:
            raise GraphQLError(f"Validation failed: {exc.message_dict}")

        # Configuration
        try:
            config = WhiteLabelConfiguration.objects.create(
                client=client,
                theme_mode=theme_mode,
                enable_ride_sharing=(
                    input["enable_ride_sharing"]
                    if input.get("enable_ride_sharing") is not None
                    else True
                ),
                enable_sustainability_tracking=(
                    input["enable_sustainability_tracking"]
                    if input.get("enable_sustainability_tracking") is not None
                    else True
                ),
                enable_accessibility_features=(
                    input["enable_accessibility_features"]
                    if input.get("enable_accessibility_features") is not None
                    else True
                ),
                enable_analytics_dashboard=(
                    input["enable_analytics_dashboard"]
                    if input.get("enable_analytics_dashboard") is not None
                    else True
                ),
                payment_gateway=payment_gateway,
                custom_domains=input.get("custom_domains") or [],
                google_analytics_id=input.get("google_analytics_id") or "",
                facebook_pixel_id=input.get("facebook_pixel_id") or "",
            )
        except ValidationError as exc:
            # The whole transaction rolls back.
            raise GraphQLError(f"Configuration invalid: {exc.message_dict}")

        return cls(
            white_label_client=client,
            white_label_configuration=config,
            api_key=api_key,
            success=True,
            message="White-label client created. Store the API key securely.",
        )


