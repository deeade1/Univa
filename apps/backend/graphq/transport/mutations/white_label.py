class UpsertWhiteLabelConfiguration(relay.ClientIDMutation):
    """
    Create or update the OneToOne configuration for a client.

    OneToOneField means the create and update paths collapse into a
    single upsert. Fields not passed are left untouched.
    """

    class Input:
        white_label_client_id = graphene.ID(required=True)

        theme_mode = graphene.String()

        enable_ride_sharing = graphene.Boolean()
        enable_sustainability_tracking = graphene.Boolean()
        enable_accessibility_features = graphene.Boolean()
        enable_analytics_dashboard = graphene.Boolean()

        payment_gateway = graphene.String()
        custom_domains = graphene.List(graphene.String)

        google_analytics_id = graphene.String()
        facebook_pixel_id = graphene.String()

    white_label_configuration = graphene.Field(WhiteLabelConfigurationNode)
    created = graphene.Boolean()
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, white_label_client_id, **input):
        _assert_staff(info.context.user)
        client = _resolve_client(white_label_client_id, lock=True)

        if "theme_mode" in input and input["theme_mode"] is not None:
            if input["theme_mode"] not in _ALLOWED_THEME_MODES:
                raise GraphQLError(
                    f"theme_mode must be one of: "
                    f"{', '.join(sorted(_ALLOWED_THEME_MODES))}."
                )

        if "payment_gateway" in input and input["payment_gateway"] is not None:
            if input["payment_gateway"] not in _ALLOWED_PAYMENT_GATEWAYS:
                raise GraphQLError(
                    f"payment_gateway must be one of: "
                    f"{', '.join(sorted(_ALLOWED_PAYMENT_GATEWAYS))}."
                )

        defaults = {}
        for input_key in (
            "theme_mode",
            "enable_ride_sharing",
            "enable_sustainability_tracking",
            "enable_accessibility_features",
            "enable_analytics_dashboard",
            "payment_gateway",
            "custom_domains",
            "google_analytics_id",
            "facebook_pixel_id",
        ):
            if input_key in input and input[input_key] is not None:
                defaults[input_key] = input[input_key]

        config, created = WhiteLabelConfiguration.objects.get_or_create(
            client=client,
            defaults=defaults,
        )

        if not created and defaults:
            for field, value in defaults.items():
                setattr(config, field, value)
            try:
                config.full_clean()
            except ValidationError as exc:
                raise GraphQLError(f"Validation failed: {exc.message_dict}")
            config.save()

        return cls(
            white_label_configuration=config,
            created=created,
            success=True,
            message="Configuration saved.",
        )


