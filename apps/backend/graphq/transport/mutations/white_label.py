class UpdateWhiteLabelClient(relay.ClientIDMutation):
    """
    Update a WhiteLabelClient's branding, content, and feature flags.

    `api_key` and `domain` are not editable here — rotate the key via
    `RegenerateWhiteLabelApiKey`, and change the domain via a separate
    operation if you support that workflow.
    """

    class Input:
        white_label_client_id = graphene.ID(required=True)

        name = graphene.String()
        company_name = graphene.String()
        support_email = graphene.String()
        support_phone = graphene.String()

        primary_color = graphene.String()
        secondary_color = graphene.String()
        font_family = graphene.String()

        terms_of_service = graphene.String()
        privacy_policy = graphene.String()

        custom_css = graphene.String()
        custom_js = graphene.String()

        enabled_features = graphene.JSONString()
        custom_features = graphene.JSONString()

        webhook_url = graphene.String()

        is_active = graphene.Boolean()

    white_label_client = graphene.Field(WhiteLabelClientNode)
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, white_label_client_id, **input):
        _assert_staff(info.context.user)
        client = _resolve_client(white_label_client_id, lock=True)

        _validate_email(input.get("support_email"), "support_email")
        _validate_url(input.get("terms_of_service"), "terms_of_service")
        _validate_url(input.get("privacy_policy"), "privacy_policy")
        _validate_url(input.get("webhook_url"), "webhook_url")
        _validate_hex_color(input.get("primary_color"), "primary_color")
        _validate_hex_color(input.get("secondary_color"), "secondary_color")

        update_fields = []

        # Scalar assignments
        scalar_map = {
            "name": "name",
            "company_name": "company_name",
            "support_email": "support_email",
            "support_phone": "support_phone",
            "primary_color": "primary_color",
            "secondary_color": "secondary_color",
            "font_family": "font_family",
            "terms_of_service": "terms_of_service",
            "privacy_policy": "privacy_policy",
            "custom_css": "custom_css",
            "custom_js": "custom_js",
            "webhook_url": "webhook_url",
        }
        for input_key, model_field in scalar_map.items():
            if input_key in input and input[input_key] is not None:
                setattr(client, model_field, input[input_key])
                update_fields.append(model_field)

        # is_active toggle
        if "is_active" in input and input["is_active"] is not None:
            client.is_active = bool(input["is_active"])
            update_fields.append("is_active")

        # JSON merges
        for input_key, model_field in (
            ("enabled_features", "enabled_features"),
            ("custom_features", "custom_features"),
        ):
            if input_key in input and input[input_key] is not None:
                if not isinstance(input[input_key], dict):
                    raise GraphQLError(f"{input_key} must be an object.")
                merged = {**(getattr(client, model_field) or {}), **input[input_key]}
                setattr(client, model_field, merged)
                update_fields.append(model_field)

        if not update_fields:
            return cls(
                white_label_client=client,
                success=True,
                message="Nothing to update.",
            )

        try:
            client.full_clean()
        except ValidationError as exc:
            raise GraphQLError(f"Validation failed: {exc.message_dict}")

        client.save(update_fields=sorted(set(update_fields + ["updated_at"])))

        return cls(
            white_label_client=client,
            success=True,
            message="White-label client updated.",
        )


