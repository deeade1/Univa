"""
White-label mutations.

Design rules enforced:
    - WhiteLabelClient creation / modification is staff-only. Clients
      are administrative entities; a regular user must not be able to
      register one.
    - `api_key` is server-generated on create and can only be
      regenerated by staff via `RegenerateWhiteLabelApiKey`.
    - `WhiteLabelConfiguration` is upserted (OneToOneField).
    - The in-memory `WhiteLabelService.client_cache` is not touched —
      mutations write directly to the ORM and rely on the service's
      per-instance cache being short-lived. If you move to a shared
      cache, invalidate here.
"""

