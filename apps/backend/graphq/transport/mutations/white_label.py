class RegenerateWhiteLabelApiKey(relay.ClientIDMutation):
    """
    Rotate a client's API key.

    Staff-only. The old key stops working immediately. If the client
    has a webhook consumer, that consumer must be updated out-of-band.
    """

    class Input:
        white_label_client_id = graphene.ID(required=True)

    white_label_client = graphene.Field(WhiteLabelClientNode)
    api_key = graphene.String()
    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, white_label_client_id):
        _assert_staff(info.context.user)
        client = _resolve_client(white_label_client_id, lock=True)

        client.api_key = _generate_api_key()
        client.save(update_fields=["api_key", "updated_at"])

        return cls(
            white_label_client=client,
            api_key=client.api_key,
            success=True,
            message="API key rotated. Deliver to the client securely.",
        )


