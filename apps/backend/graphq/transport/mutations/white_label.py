class DeleteWhiteLabelClient(relay.ClientIDMutation):
    """
    Delete a WhiteLabelClient.

    Staff-only. The configuration cascades (`on_delete=CASCADE` on the
    OneToOneField). Prefer deactivating (`is_active=False`) for
    temporary removal — deletion is irreversible and drops any
    downstream references.
    """

    class Input:
        white_label_client_id = graphene.ID(required=True)

    success = graphene.Boolean()
    message = graphene.String()

    @classmethod
    @transaction.atomic
    def mutate_and_get_payload(cls, root, info, white_label_client_id):
        _assert_staff(info.context.user)
        client = _resolve_client(white_label_client_id, lock=True)

        try:
            client.delete()
        except Exception as exc:
            raise GraphQLError(
                f"Delete blocked — client has related records: {exc}"
            )

        return cls(success=True, message="White-label client deleted.")


