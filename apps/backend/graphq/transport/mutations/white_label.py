# Helpers
# =============================================================================

def _assert_staff(user):
    if not user.is_authenticated:
        raise GraphQLError("Authentication required.")
    if not user.is_staff:
        raise GraphQLError("Staff permission required.")


def _resolve_client(global_id, *, lock=False):
    try:
        _, pk = from_global_id(global_id)
    except Exception:
        raise GraphQLError("Invalid white_label_client_id.")
    qs = WhiteLabelClient.objects.all()
    if lock:
        qs = qs.select_for_update()
    try:
        return qs.get(pk=pk)
    except WhiteLabelClient.DoesNotExist:
        raise GraphQLError("White-label client not found.")


def _generate_api_key():
    """Generate a secure, unique API key."""
    for _ in range(5):
        candidate = secrets.token_urlsafe(32)
        if not WhiteLabelClient.objects.filter(api_key=candidate).exists():
            return candidate
    raise GraphQLError("Could not generate a unique API key. Try again.")


def _validate_hex_color(value, field):
    if value is None:
        return
    if not isinstance(value, str) or len(value) != 7 or not value.startswith("#"):
        raise GraphQLError(f"{field} must be a 7-character hex color like #3B82F6.")
    try:
        int(value[1:], 16)
    except ValueError:
        raise GraphQLError(f"{field} must be a valid hex color.")


def _validate_url(value, field):
    if value is None or value == "":
        return
    validator = URLValidator()
    try:
        validator(value)
    except ValidationError:
        raise GraphQLError(f"{field} must be a valid URL.")


def _validate_email(value, field):
    if value is None or value == "":
        return
    from django.core.validators import EmailValidator
    try:
        EmailValidator()(value)
    except ValidationError:
        raise GraphQLError(f"{field} must be a valid email address.")


